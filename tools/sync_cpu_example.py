"""Run the landing page's CPU example and write it, with its real output, to ``_generated/what_you_write_cpu.md``.

Usage (from the site root, in an environment where ``eagle`` and ``hawk`` import)::

    python tools/sync_cpu_example.py

The example is ``_data/what_you_write_cpu.py`` (the GPU example's NumPy twin, a thousand samples). It runs
with no GPU visible, so the output on the page is what a CPU-only reader gets; nothing about it is typed by
hand. Maintenance-time only, like ``sync_cards.py``: the site's own CI reads the committed file.
"""
import os
import pathlib
import subprocess
import sys

SITE_ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = SITE_ROOT / "_data" / "what_you_write_cpu.py"
OUT = SITE_ROOT / "_generated" / "what_you_write_cpu.md"


def render(source_text, output_text):
    """The MyST include: the code block, then its printed output."""
    return ("<!-- Generated by tools/sync_cpu_example.py; do not edit. -->\n\n"
            f"```python\n{source_text.rstrip()}\n```\n\n"
            f"Printed on a CPU:\n\n```text\n{output_text.rstrip()}\n```\n")


def main(out=OUT):
    source = SOURCE.read_text()
    env = dict(os.environ, CUDA_VISIBLE_DEVICES="")
    proc = subprocess.run([sys.executable, "-I", "-c", "import sys; exec(compile(open(sys.argv[1]).read(), sys.argv[1], 'exec'))", str(SOURCE)],
                          env=env, capture_output=True, text=True, timeout=600, cwd=SITE_ROOT)
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        return proc.returncode
    pathlib.Path(out).write_text(render(source, proc.stdout))
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
